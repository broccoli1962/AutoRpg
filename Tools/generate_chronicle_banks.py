def expand_to_count(base: list[str], count: int, prefix: str) -> list[str]:
    out = []
    for i in range(count):
        out.append(base[i % len(base)] if i < len(base) else f"{prefix} 변형 {i + 1}")
    return out


def assign_tags(index: int, total: int) -> list[str]:
    if index % 7 == 0:
        return []
    return [PERSONALITIES[index % len(PERSONALITIES)]]


def build_entries(texts: list[str]) -> list[dict]:
    entries = []
    for i, text in enumerate(texts):
        tags = assign_tags(i, len(texts))
        weight = 2 if tags else 1
        entries.append({"text": text, "weight": weight, "conditionTags": tags})
    return entries


def generate_event(event_type: str, theme: dict) -> dict:
    slots = {}
    for slot_name, count in SLOT_COUNTS.items():
        base = theme[slot_name]
        texts = expand_to_count(base, count, slot_name)
        slots[slot_name] = build_entries(texts)
    return {"eventType": event_type, "slots": slots}


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for event_type, theme in EVENT_THEMES.items():
        data = generate_event(event_type, theme)
        counts = {s: len(data["slots"][s]) for s in SLOT_COUNTS}
        product = 1
        for c in counts.values():
            product *= c
        path = os.path.join(OUTPUT_DIR, f"{event_type}.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"{event_type}: {counts} => {product} combinations -> {path}")


if __name__ == "__main__":
    main()
